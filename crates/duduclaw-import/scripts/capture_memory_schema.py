"""Reproduce the fresh current (v1.80.x line) memory schema from reviewed Rust SQL literals,
without opening user data. Run from repository root. A changed engine requires reviewing the
resulting fixture diff. Writes memory-v180.sql; memory-v1793.sql is the pinned older catalog
and is never regenerated from current source.
"""
import pathlib, re, sqlite3
root=pathlib.Path('crates/duduclaw-memory/src')
def literals(text):
    return [m.group(1).replace('\\n','\n').replace('\\"','"').replace('\\\\','\\') for m in re.finditer(r'"((?:\\.|[^"\\])*)"',text)]
engine=(root/'engine.rs').read_text().split('    fn init_tables(conn: &Connection)')[1].split('    /// Parse a row')[0]
lineage=(root/'lineage/db.rs').read_text()
connectors=(root/'lineage/connectors.rs').read_text().split('pub(crate) fn migrate')[1].split('#[cfg(test)]')[0]
conn=sqlite3.connect(':memory:'); statements=[]
def run(sql):
    try: conn.executescript(sql)
    except sqlite3.OperationalError as error:
        if str(error).startswith('duplicate column name:'): return
        raise
    statements.append(sql)
for sql in literals(engine):
    if sql.strip().startswith(('CREATE ','ALTER ')):run(sql)
run(next(s for s in literals(lineage) if s.startswith('CREATE TABLE IF NOT EXISTS memory_origins')))
expr=next(s for s in literals(lineage) if s.startswith('(EXISTS (SELECT 1 FROM {fs}'))
expr=expr.format(fs='forgotten_sources',agent='NEW.agent_id',session='NEW.source_session',message='NEW.source_message',seq='NEW.source_seq',observed='NEW.source_observed_at')
trigger=next(s for s in literals(lineage) if s.startswith('CREATE TRIGGER IF NOT EXISTS trg_origins_fence'))
run(trigger.replace('{}',expr))
for sql in literals(connectors):
    if sql.startswith('SAVEPOINT connector_schema_v4;'):
        run(sql.replace('SAVEPOINT connector_schema_v4;',''))
    elif sql.startswith('DROP TRIGGER IF EXISTS trg_connector_stamp_fence;'): run(sql)
    elif sql.startswith('CREATE INDEX IF NOT EXISTS idx_disconnect_forget_due'):
        for col,definition in [('attempt_count','INTEGER NOT NULL DEFAULT 0'),('next_attempt_at','INTEGER NOT NULL DEFAULT 0'),('retry_status','TEXT')]:
            run(f'ALTER TABLE disconnect_forget_batches ADD COLUMN {col} {definition};')
        run(sql)
    elif sql.startswith('UPDATE memory_connector_stamps SET connector_observed_at=COALESCE('):
        run(sql.replace('RELEASE connector_schema_v4;',''))
# Store the creation/migration statements, preserving original SQLite SQL spelling.
HEADER=('-- Fresh engine schema of the current (v1.80.x line) memory store; generated by scripts/capture_memory_schema.py.\n'
        '-- memory-v1793.sql is the pinned older catalog and is never regenerated. Difference: RM-039 idx_memories_subject_ts.\n')
pathlib.Path('crates/duduclaw-import/src/memory-v180.sql').write_text(HEADER+'\n'.join(s.strip()+';' if not s.rstrip().endswith(';') else s.strip() for s in statements)+'\n')
print('schema objects:',conn.execute('SELECT count(*) FROM sqlite_schema').fetchone()[0])
