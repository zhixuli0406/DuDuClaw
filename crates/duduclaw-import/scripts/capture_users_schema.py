"""Capture reviewed pre-migration auth DDL, never user data. Run from repo root."""
import pathlib,re,sqlite3,subprocess
root=pathlib.Path('crates/duduclaw-auth/src')
def source(name):
    # Base commit excludes Package G's newly-added setup/proof schema.
    return subprocess.check_output(['git','show','HEAD:crates/duduclaw-auth/src/'+name],text=True)
def literals(text):
    return [m.group(1).replace('\\n','\n').replace('\\"','"').replace('\\\\','\\') for m in re.finditer(r'"((?:\\.|[^"\\])*)"',text)]
conn=sqlite3.connect(':memory:');statements=[]
def run(sql):
    try:conn.executescript(sql)
    except sqlite3.OperationalError as e:
        if str(e).startswith('duplicate column name:'):return
        raise
    statements.append(sql)
db=source('db.rs').split('    fn init_tables(')[1].split('    /// Set a personal preference')[0]
sqls=literals(db)
run(next(s for s in sqls if s.startswith('CREATE TABLE IF NOT EXISTS users')))
for name in ['google_identity.rs','mfa.rs','user_invites.rs']:
    text=source(name).split('pub(crate) fn migrate(')[1]
    text=text.split('\n#[derive')[0] if name!='mfa.rs' else text.split('\n// Read under')[0]
    for sql in literals(text):
        if sql.startswith(('CREATE ','ALTER ')):run(sql)
for sql in sqls:
    if sql.startswith('ALTER ') or sql.startswith('CREATE INDEX IF NOT EXISTS idx_users_manager'):run(sql)
pathlib.Path('crates/duduclaw-import/src/users-v1793.sql').write_text('-- Reviewed legacy auth schema; generated by scripts/capture_users_schema.py.\n'+'\n'.join(s.strip()+';' if not s.rstrip().endswith(';') else s.strip() for s in statements)+'\n')
print('schema objects:',conn.execute('SELECT count(*) FROM sqlite_schema').fetchone()[0])
