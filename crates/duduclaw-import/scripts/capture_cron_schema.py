"""Extract the reviewed CronStore initializer (v1.79.3 + v1.80 scoped-creator
columns and creation receipts), never legacy bytes.

Writes cron-v180.sql: the current source is the v1.80.x store. cron-v1793.sql is
a separate pinned catalog of the older release and is never regenerated from
current source (see its header for how it was derived)."""
from pathlib import Path
import re
ROOT = Path(__file__).resolve().parents[3]
source = (ROOT / "crates/duduclaw-gateway/src/cron_store.rs").read_text()
initializer = source.split("    fn init_schema(conn: &Connection)", 1)[1].split("    // ── Reads", 1)[0]
blocks = re.findall(r'execute_batch\(\s*"((?:\\.|[^"\\])*)"', initializer, re.S)
assert len(blocks) == 3
columns = ["notify_channel", "notify_chat_id", "notify_thread_id", "cron_timezone", "trigger_kind", "condition_script", "condition_state", "watch_command", "on_behalf_of", "created_by_user_id", "scoped_by_user_id"]
for column in columns:
    assert f'"{column}"' in initializer
sql = ("\n\n".join(blocks[:2]) + "\n" + "\n".join(f"ALTER TABLE cron_tasks ADD COLUMN {column} TEXT;" for column in columns)
       + "\n" + blocks[2] + ";")
HEADER = ("-- Exact CronStore initializer and ordered additive columns of a v1.80.x cron_tasks.db\n"
          "-- (v1.79.3 base plus the v1.80.0 scoped creator: created_by_user_id, scoped_by_user_id,\n"
          "-- cron_creation_receipts and the scoped indexes). Generated by scripts/capture_cron_schema.py.\n")
(ROOT / "crates/duduclaw-import/src/cron-v180.sql").write_text(HEADER + sql + "\n")
