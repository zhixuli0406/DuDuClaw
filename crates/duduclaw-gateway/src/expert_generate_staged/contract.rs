//! CONTRACT.toml for generated team members.
//!
//! `must_not` is not only prompt guidance: the runtime also matches every
//! rule as a case-insensitive SUBSTRING (or a glob, when it carries `*` `?`
//! `[`) against the final text of each channel reply and blocks the reply on
//! a hit (`duduclaw_agent::contract::validate_response`). A short keyword
//! rule such as 「退款」 would therefore block every reply that merely
//! mentions refunds. Model-written rules are sanitized here so they stay
//! descriptive sentences:
//!
//! - glob metacharacters are removed (a model must never author a pattern);
//! - rules shorter than [`MIN_MUST_NOT_CHARS`] are dropped;
//! - length, count and duplicates are capped.

use std::collections::BTreeSet;

use crate::expert_generate::GeneratedContract;

/// Shortest `must_not` rule kept (chars). Shorter rules are keyword-like and
/// would false-positive on ordinary replies.
pub const MIN_MUST_NOT_CHARS: usize = 10;
const MAX_RULE_CHARS: usize = 160;
const MIN_MUST_ALWAYS_CHARS: usize = 4;
const MAX_RULES: usize = 8;

fn normalize_rule(raw: &str) -> String {
    let flat: String = raw
        .chars()
        .map(|c| if c.is_whitespace() { ' ' } else { c })
        .filter(|c| !matches!(c, '*' | '?' | '[' | ']'))
        .collect();
    let collapsed = flat.split_whitespace().collect::<Vec<_>>().join(" ");
    duduclaw_core::truncate_chars(collapsed.trim(), MAX_RULE_CHARS)
}

fn sanitize_list(rules: &[String], min_chars: usize) -> Vec<String> {
    let mut seen = BTreeSet::new();
    rules
        .iter()
        .map(|r| normalize_rule(r))
        .filter(|r| r.chars().count() >= min_chars)
        .filter(|r| seen.insert(r.clone()))
        .take(MAX_RULES)
        .collect()
}

/// Return a sanitized copy (never mutates the input).
pub fn sanitize_contract(c: &GeneratedContract) -> GeneratedContract {
    GeneratedContract {
        must_not: sanitize_list(&c.must_not, MIN_MUST_NOT_CHARS),
        must_always: sanitize_list(&c.must_always, MIN_MUST_ALWAYS_CHARS),
    }
}

/// Render a CONTRACT.toml body, or `None` when the sanitized contract has no
/// rules at all (no file is better than an empty one: `duduclaw test`
/// reports an empty contract as a failed check either way).
pub fn render_contract_toml(c: &GeneratedContract) -> Option<String> {
    use toml::Value as T;
    let c = sanitize_contract(c);
    if c.must_not.is_empty() && c.must_always.is_empty() {
        return None;
    }
    let mut boundaries = toml::value::Table::new();
    boundaries.insert(
        "must_not".into(),
        T::Array(c.must_not.into_iter().map(T::String).collect()),
    );
    boundaries.insert(
        "must_always".into(),
        T::Array(c.must_always.into_iter().map(T::String).collect()),
    );
    let mut root = toml::value::Table::new();
    root.insert("boundaries".into(), T::Table(boundaries));
    let body = toml::to_string_pretty(&T::Table(root)).ok()?;
    Some(format!(
        "# Generated by DuDuClaw expert authoring — AI 產生草稿，請管理者核對。\n\
         # must_not 也會逐字比對每則通道回覆，命中時該則回覆會被擋下。\n{body}"
    ))
}

#[cfg(test)]
mod tests {
    use super::*;

    fn c(must_not: &[&str], must_always: &[&str]) -> GeneratedContract {
        GeneratedContract {
            must_not: must_not.iter().map(|s| s.to_string()).collect(),
            must_always: must_always.iter().map(|s| s.to_string()).collect(),
        }
    }

    #[test]
    fn short_keyword_rules_and_globs_are_neutralized() {
        let out = sanitize_contract(&c(
            &[
                "退款",                                 // keyword → dropped
                "*保證*獲利*",                          // glob chars stripped → too short
                "替客戶決定要不要退費或承諾退費金額",   // kept
                "替客戶決定要不要退費或承諾退費金額",   // duplicate
                "對外說出\n未公開的進貨成本與毛利數字", // newline flattened
            ],
            &["要", "涉及金額一律轉交真人確認"],
        ));
        assert_eq!(
            out.must_not,
            vec![
                "替客戶決定要不要退費或承諾退費金額".to_string(),
                "對外說出 未公開的進貨成本與毛利數字".to_string(),
            ]
        );
        assert_eq!(out.must_always, vec!["涉及金額一律轉交真人確認".to_string()]);
        for r in &out.must_not {
            assert!(!r.contains(['*', '?', '[', ']']), "{r}");
        }
    }

    #[test]
    fn rendered_contract_parses_with_the_runtime_parser() {
        let toml_src = render_contract_toml(&c(
            &["替客戶決定要不要退費或承諾退費金額"],
            &["涉及金額一律轉交真人確認"],
        ))
        .expect("non-empty contract renders");
        let parsed: duduclaw_agent::contract::Contract = toml::from_str(&toml_src).unwrap();
        assert_eq!(parsed.boundaries.must_not.len(), 1);
        assert_eq!(parsed.boundaries.must_always.len(), 1);
        // The runtime output filter must not fire on an ordinary refusal.
        let v = duduclaw_agent::contract::validate_response(
            &parsed,
            "這部分我沒辦法替您決定，我先幫您轉給店長確認。",
        );
        assert!(v.passed, "{:?}", v.violations);
    }

    #[test]
    fn empty_contract_renders_nothing() {
        assert!(render_contract_toml(&c(&["短"], &[])).is_none());
    }
}
