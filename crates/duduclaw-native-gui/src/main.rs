// DuDuClaw Native GUI — Phase 1a.
//
// Phase 0a (see git history for the original single-file version this
// replaced) proved gpui builds + runs on this machine and that a background
// thread can bridge a WebSocket connection to the local gateway into the
// gpui UI thread. Phase 1a builds the first real UI on top of that
// foundation: language-picker-first entry → login screen → app shell
// (sidebar + routing + content area).
//
// Design language: MDS (Multica-derived Design System) — re-skinned from
// the original "Calm Glass" pass per client feedback ("版面/配色/間距/字體都
// 不對", 2026-08). Source of truth: `commercial/docs/multica-redesign-
// spec.md` + `web/src/index.css`'s shipped OKLCH tokens, converted to sRGB
// hex in `theme.rs` (see that file's module doc comment for the conversion
// methodology and verification). NOT `web/DESIGN.md` / the root `CLAUDE.md`
// "Design Context" section anymore — those describe the superseded Calm
// Glass language.
//
// ── gpui API gotchas learned so far (do NOT rediscover these) ───────────
// Verified against the local gpui git checkout
// (~/.cargo/git/checkouts/zed-*, rev 7a7c3e1, 2026-08-19):
//   - Entry point is `gpui_platform::application()`, NOT `Application::new()`.
//   - `Styled` box methods (`p_*`, `gap_*`, `size_*`, `w_*`, `h_*`, `m_*`,
//     `rounded_*`) are a FIXED Tailwind-preset ramp generated by
//     `gpui_macros::style_helpers!()` (`crates/gpui_macros/src/styles.rs`
//     `box_style_suffixes()` / `corner_suffixes()`) — there is no free-form
//     `.p(px(24.))`. But the SAME macros also emit an arbitrary-value
//     "custom setter" per prefix (`.w(px(480.))`, `.pl(px(26.))`,
//     `.text_size(px(15.))`, `.bg(rgb(...))`, `.text_color(rgb(...))`,
//     `.border_color(rgb(...))` — these take real `Pixels`/`Into<Hsla>`
//     values). `crates/gpui/examples/popover.rs` and `focus_visible.rs` are
//     the clearest references for which is which.
//   - `cx.spawn(async move |cx: &mut AsyncApp| ...)` for background-thread
//     bridges (see `ws_status.rs` + the poll loop below); update entities
//     via `WindowHandle::update` / `Entity::update` + `cx.notify()`.
//   - `cx.listener(|this: &mut V, event, window, cx: &mut Context<V>| ...)`
//     (`crates/gpui/src/app/context.rs`) is how a click/key handler gets
//     mutable access to view state — it downgrades+upgrades the entity, so
//     it's safe to store on `Div` builders directly via `.on_click(...)`.
//   - `.id("stable-id")` is required before `.on_click(...)` (every
//     interactive-but-clickable example does this;
//     `StatefulInteractiveElement` needs an `ElementId`).
//   - A `&mut Context<V>` is NOT `Copy`, so it cannot be captured into a
//     closure that runs more than once (e.g. `Iterator::map` building a
//     `Vec` of rows) — use a plain `for` loop instead (each iteration
//     re-borrows fresh). See `screens/language_picker.rs` and
//     `screens/shell.rs` for the pattern.
//   - No CSS `backdrop-filter` equivalent exists in gpui's style system
//     (only `BoxShadow::blur_radius` for drop shadows) — MDS's own alpha-
//     modifier tokens (`bg-foo/NN`) are approximated with translucent solid
//     colors (`theme::alpha`), not a true blur, but MDS itself barely leans
//     on blur outside the Dialog overlay, which Phase 1a doesn't implement.
//   - `Entity<T: Render>` implements `IntoElement` directly, so a child
//     entity (e.g. a `TextField`) can be passed straight to `.child(...)`.
//   - `Styled::text_color()` / `::border_color()` take `impl Into<Hsla>` —
//     `Rgba` (what `rgb()`/`rgba()`/`theme::alpha()` return) satisfies that
//     bound directly, so pass it AS-IS. Calling `.into()` on it yourself
//     makes the target ambiguous (`Rgba` also implements `Into<Fill>`,
//     `Into<Background>`, `Into<u32>`, `Into<HighlightStyle>`) and fails to
//     compile with "type annotations needed" UNLESS something else in the
//     same expression anchors the type (e.g. the other arm of an `if/else`
//     already being a concrete `Hsla`, as in `text_field.rs`'s border color).
//   - `.id(...)` changes an element's concrete type from `Div` to
//     `Stateful<Div>` — a helper function that calls `.id(...)` and is
//     later used with `.on_click(...)` must declare `-> Stateful<Div>`, not
//     `-> Div`, or the return-type check fails (`screens/language_picker.rs`
//     `locale_card`, `screens/shell.rs` `nav_row`).
//
// First build after adding deps is slow; incremental builds are seconds.
// ALWAYS build/run with the arm64 toolchain pinned by `rust-toolchain.toml`
// (1.97.1) — plain `cargo`/`rustc` on PATH is Homebrew's x86_64 build and
// silently produces an x86_64 binary that panics on architecture-sensitive
// build scripts deep in gpui's dependency tree (`media`'s bindgen step,
// which dlopens Xcode's arm64-only libclang.dylib).
//
// IMPORTANT (found the hard way in this session — the crate's own
// documented fix, `rustup run stable-aarch64-apple-darwin cargo build`,
// does NOT reliably work): `rustup run <toolchain> cargo` only guarantees
// the *cargo* binary itself is correct — cargo then resolves `rustc` via a
// bare PATH lookup (`Command::new("rustc")`, no absolute path), and if a
// Homebrew/system `rustc` sits earlier on PATH than the rustup shim dir
// (true on this machine: `/usr/local/bin` before `~/.cargo/bin`), the
// ACTUAL compiler used for build scripts is silently the wrong x86_64 one
// even though `cargo -vV` reports the right host. Symptom: `media`'s build
// script panics with "libclang ... incompatible architecture (have arm64,
// need x86_64)" — the smoking gun is `file target/debug/build/media-*/
// build-script-build` reporting `x86_64` executable. Root-caused by running
// `cargo build -vv` and finding `HOST=x86_64-apple-darwin` / bare
// `RUSTC=rustc` in the env cargo hands to the build script. The reliable
// fix, used for every build/run in this session:
//   export PATH="$HOME/.rustup/toolchains/1.97.1-aarch64-apple-darwin/bin:$PATH"
//   export RUSTC="$HOME/.rustup/toolchains/1.97.1-aarch64-apple-darwin/bin/rustc"
//   cargo build   # (now resolves correctly, arm64 end to end)
// After a wrong-arch attempt, `rm -rf target` before switching — the two
// architectures' build-script artifacts share the same `target/debug/`
// directory (no explicit `--target` is passed) and do not safely coexist.

