/// Which of the three Phase 1a screens is currently showing.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Screen {
    Language,
    Login,
    Shell,
}

pub struct RootView {
    screen: Screen,
    locale: Locale,
    ws_state: WsConnState,
    email_field: Entity<TextField>,
    password_field: Entity<TextField>,
    /// Currently-selected sidebar nav item id (see `nav.rs`), used once
    /// `screen == Screen::Shell`.
    active_page: &'static str,
    /// S4a: which of the 13 static prototype pages is selected inside the
    /// "設計稿" design gallery (`screens/prototypes/mod.rs`). Only
    /// meaningful when `active_page == "designGallery"`; otherwise unused —
    /// initialized to the gallery's first entry either way.
    active_prototype: &'static str,
    /// P0-1: whether `screens/shell.rs`'s Column 1 (the area rail) is
    /// hidden. Toggled by the macOS menu bar's View ▸ Show/Hide Sidebar
    /// action (`native_menu.rs`) — no other UI trigger exists yet, so on
    /// non-macOS builds this stays permanently `false` (honest stub: no
    /// persistence either, matches this crate's existing `jwt`/
    /// `refresh_token` "S2 scope stops here" precedent above).
    sidebar_collapsed: bool,
    /// Command channel into the background session manager (`ws_status.rs`)
    /// — cloned into click handlers that need to trigger a login or a WS
    /// (re)connect.
    session_tx: tokio_mpsc::UnboundedSender<SessionCommand>,
    /// Access token, in memory only. S2 scope stops here deliberately: no
    /// disk persistence, no refresh timer — see this crate's final S2
    /// report for the explicit S3+ "honest stub" callout on refresh-token
    /// handling.
    #[allow(dead_code)] // not yet read anywhere past the ConnectWs dispatch that consumes it
    jwt: Option<String>,
    /// Refresh token, in memory only (task item 5: "本階段只存於記憶體、不做自動
    /// refresh timer"). S2 captures it so it exists when an S3+ refresh
    /// timer is wired up, but nothing reads it yet — the 30-min access
    /// token this crate currently obtains simply goes stale unrefreshed on
    /// a long-running session, exactly like the "honest stub" this field's
    /// name promises.
    #[allow(dead_code)]
    refresh_token: Option<String>,
    /// True while a `login`/local-session HTTP call is in flight — drives
    /// the submit button's loading/disabled state.
    login_loading: bool,
    /// Localized error line shown under the login form, if the last
    /// attempt failed.
    login_error: Option<SharedString>,
    /// S4: the chat page's own state (messages, connection status, the
    /// IME-capable composer entity, ...) — see `screens/chat.rs`'s doc
    /// comment for why this is one bundled field, not a dozen flat ones.
    chat: screens::chat::ChatState,
    /// S4b: the dashboard page's own per-card fetch state — see
    /// `screens/dashboard.rs`'s module doc comment.
    dashboard: screens::dashboard::DashboardState,
    /// The logged-in user's `display_name` (`api::AuthUser`), captured from
    /// the local-session/login response for the dashboard greeting line.
    /// `None` until a session actually resolves; the greeting falls back to
    /// a generic name rather than showing nothing (see `screens::dashboard::
    /// greeting_name`).
    display_name: Option<String>,
}

impl RootView {
    /// Apply one event from the background session manager. Pulled out of
    /// the `cx.spawn` poll loop in `main()` so the state-transition logic
    /// is unit-testable-in-spirit (pure `&mut self` mutation) and readable
    /// in one place rather than inline in a closure.
    fn handle_session_event(&mut self, event: SessionEvent) {
        match event {
            SessionEvent::LocalSessionOk(resp) => {
                // Guard against the (practically impossible, but cheap to
                // guard) race where a manual login already completed
                // before this boot-time probe resolved — never let a stale
                // local-session token clobber a fresh interactive login.
                if self.jwt.is_some() {
                    return;
                }
                self.jwt = Some(resp.access_token.clone());
                self.refresh_token = Some(resp.refresh_token);
                self.screen = Screen::Shell;
                self.login_error = None;
                // S4b: for the dashboard greeting line — see that field's
                // own doc comment.
                self.display_name = Some(resp.user.display_name.clone());
                // S4: the chat socket authenticates eagerly right alongside
                // the main `/ws`, same timing — by the time a user actually
                // navigates to the chat page it's normally already
                // connected, not connecting-on-first-open.
                self.chat.connect(resp.access_token.clone());
                let _ = self.session_tx.send(SessionCommand::ConnectWs {
                    jwt: resp.access_token,
                });
            }
            SessionEvent::LocalSessionUnavailable => {
                // Silent — matches `auth-store.ts`'s `tryLocalSession()`
                // policy exactly: a refusal here is expected on every
                // install that isn't a Personal loopback box, and must
                // never surface as an error. Whatever screen locale
                // resolution already picked (Language or Login) just stays.
            }
            SessionEvent::LoginOk(resp) => {
                self.jwt = Some(resp.access_token.clone());
                self.refresh_token = Some(resp.refresh_token);
                self.screen = Screen::Shell;
                self.login_loading = false;
                self.login_error = None;
                self.display_name = Some(resp.user.display_name.clone());
                self.chat.connect(resp.access_token.clone());
                let _ = self.session_tx.send(SessionCommand::ConnectWs {
                    jwt: resp.access_token,
                });
            }
            SessionEvent::LoginErr(err) => {
                self.login_loading = false;
                // `Other`'s `detail` is diagnostic-only (raw server error
                // text / reqwest error message) — never shown to the user
                // (the UI only ever gets the localized `{code}` message),
                // but it must not be silently dropped either (honest-
                // reporting convention: a failure's detail belongs in the
                // logs even when the UI necessarily shows a generic line).
                if let crate::api::AuthError::Other { status, detail } = &err {
                    eprintln!("[auth] login failed: status={status:?} detail={detail}");
                }
                let (key, code) = err.i18n_key_and_code();
                self.login_error = Some(if code.is_empty() {
                    i18n::t(self.locale, key)
                } else {
                    i18n::t1(self.locale, key, "code", &code)
                });
            }
            SessionEvent::WsState(state) => {
                self.ws_state = state;
            }
            SessionEvent::WsAuthFailed => {
                // Terminal per `ws_status.rs`'s own contract: the manager
                // has already stopped retrying with this (rejected) token.
                // Recovery requires a fresh `Login`, so kick the user back
                // to the login form rather than spinning silently.
                self.jwt = None;
                self.refresh_token = None;
                self.ws_state = WsConnState::Disconnected;
                self.screen = Screen::Login;
                self.login_error = Some(i18n::t(self.locale, "login.error.sessionExpired"));
                // The chat socket's JWT is now stale too — tear it down
                // rather than let it keep retrying a token the server just
                // rejected on the main `/ws` (same "auth 失敗 不無限重試"
                // reasoning `ws_status.rs` already applies to itself).
                self.chat.disconnect();
            }
            SessionEvent::ServerEvent { event, payload } => {
                // S4: no page subscribes to any particular server-pushed
                // event yet (the RPC call layer is new infrastructure this
                // pass, not consumed by the chat screen — that talks over
                // its own separate `/ws/chat` socket, see `chat_ws.rs`).
                // Logged rather than silently dropped so the plumbing is
                // observably alive even with zero consumers today.
                eprintln!("[main] server event on main /ws (no subscriber yet): {event} {payload}");
            }
        }
    }

    /// Apply one event from the background chat session manager
    /// (`chat_ws.rs`). Mirrors `handle_session_event`'s shape/placement —
    /// pulled out of the poll loop for the same readability reason.
    fn handle_chat_event(&mut self, event: chat_ws::Event) {
        self.chat.apply(event);
    }
}

impl Render for RootView {
    fn render(&mut self, _window: &mut Window, cx: &mut Context<Self>) -> impl IntoElement {
        // `self` reborrows as `&RootView` here (implicit `&mut T -> &T`
        // reborrow at the call site) — the screens only need to READ state
        // to render; mutation happens later, inside the `cx.listener`
        // closures they attach to clickable rows, which receive their own
        // fresh `&mut RootView` from the entity system when actually
        // invoked. All three screen `render` fns return the same concrete
        // `gpui::Div` type so the match arms unify without needing a boxed
        // `AnyElement`.
        let screen = match self.screen {
            Screen::Language => screens::language_picker::render(self, cx),
            Screen::Login => screens::login::render(self, cx),
            Screen::Shell => screens::shell::render(self, cx),
        };
        // S3: `.font(...)` applies at this single common ancestor of every
        // screen so the bundled font stack (`theme::app_font()`, see that
        // fn's doc comment) cascades to all text below — one call site
        // instead of repeating it in every `screens::*::render` fn.
        gpui::div().size_full().font(theme::app_font()).child(screen)
    }
}

fn main() {
    eprintln!("[main] starting duduclaw-native-gui S2");

    // Spawn the background session manager (HTTP login/local-session +
    // auto-reconnecting authenticated WS) before opening the window, and
    // fire the boot-time local-session probe immediately — its result
    // (arriving async, polled below) decides whether the user ever sees
    // the login form at all (task item 3: "啟動時先背景試 local session，成功
    // 直接進殼（跳過登入）").
    let (session_tx, session_rx) = ws_status::spawn();
    let _ = session_tx.send(SessionCommand::TryLocalSession);

    // S4: the dedicated chat socket manager — its own background thread/
    // runtime, independent of the session manager above (see `chat_ws.rs`'s
    // module doc comment for why separate, not shared).
    let (chat_tx, chat_rx) = chat_ws::spawn();

    // Locale persistence (task item 4): a resolvable saved locale skips
    // straight to the login screen; anything else (first launch, unreadable
    // file, unrecognized code) falls back to the language picker exactly as
    // Phase 1a always did. `config::load_locale` is fail-open by
    // construction — see its doc comment — so this can never block startup.
    let (initial_locale, initial_screen) = match config::load_locale() {
        Some(locale) => (locale, Screen::Login),
        None => (Locale::default(), Screen::Language),
    };
    eprintln!(
        "[main] initial locale={initial_locale:?} screen={initial_screen:?} \
         (persisted locale {})",
        if initial_screen == Screen::Login { "found" } else { "not found" }
    );

    eprintln!("[main] calling application().run(...)");
    application().run(move |cx: &mut App| {
        // S3: register the bundled font stack BEFORE opening the window —
        // any text laid out before `add_fonts` returns would resolve
        // against gpui's `.SystemUIFont` default and never re-flow onto the
        // bundled faces (there's no reactive re-layout-on-font-load here).
        // `Cow::Borrowed` avoids copying the `include_bytes!` static data;
        // `add_fonts` takes ownership only of the `Vec`/`Cow` wrapper.
        //
        // Fail-open per this crate's established convention (`config::
        // load_locale`'s doc comment): a font-loading failure must not
        // block the window from opening at all — text simply falls back to
        // gpui's system-font default for this run, logged loudly to stderr
        // rather than silently swallowed or panicking.
        let font_bytes: Vec<std::borrow::Cow<'static, [u8]>> = vec![
            std::borrow::Cow::Borrowed(include_bytes!("../assets/fonts/InterVariable.ttf").as_slice()),
            std::borrow::Cow::Borrowed(
                include_bytes!("../assets/fonts/NotoSansTC-Variable.ttf").as_slice(),
            ),
        ];
        match cx.text_system().add_fonts(font_bytes) {
            Ok(()) => eprintln!("[main] add_fonts ok: InterVariable + NotoSansTC-Variable loaded"),
            Err(e) => eprintln!("[main] add_fonts FAILED (falling back to system font): {e}"),
        }

        // Debug-only boot override, NOT part of the normal user flow: lets a
        // headless verification run (this crate has no scriptable UI-click
        // automation available — no accessibility/CI driver wired up) land
        // directly on a specific Shell nav page instead of always starting
        // at Language/Login, so a real `RootView::render` pass over that
        // page's actual code path can be observed in stderr rather than
        // just asserted from reading the click-handler source. Unset by
        // default; `DUDUCLAW_NATIVE_GUI_DEBUG_PAGE=componentLibrary` (any
        // valid `nav.rs` id) is the only way to trigger it.
        //
        // S4a extension: two more forms reach the design gallery —
        // `DUDUCLAW_NATIVE_GUI_DEBUG_PAGE=designGallery` boots into the
        // gallery on its first prototype, and `=proto:p08` boots straight
        // into that one prototype (skipping a manual click through the
        // 13-row list) — the form the S4a live-verification pass actually
        // uses to exercise each of the 13 pages in turn.
        let debug_page: Option<&'static str> = std::env::var("DUDUCLAW_NATIVE_GUI_DEBUG_PAGE")
            .ok()
            .filter(|s| !s.is_empty())
            .map(|s| -> &'static str { Box::leak(s.into_boxed_str()) });
        let (debug_active_page, debug_active_prototype): (Option<&'static str>, Option<&'static str>) =
            match debug_page {
                None => (None, None),
                Some(raw) => match raw.strip_prefix("proto:") {
                    Some(proto_id) => (Some("designGallery"), Some(proto_id)),
                    None if raw == "designGallery" => (Some("designGallery"), None),
                    None => (Some(raw), None),
                },
            };
        if let Some(page) = debug_page {
            eprintln!(
                "[main] DUDUCLAW_NATIVE_GUI_DEBUG_PAGE set — booting straight into Shell/{} (prototype={:?})",
                debug_active_page.unwrap_or(page),
                debug_active_prototype,
            );
        }

        eprintln!("[main] inside App closure, opening window");
        let bounds = Bounds::centered(None, gpui::size(px(1440.0), px(960.0)), cx);
        let session_tx_for_view = session_tx.clone();
        let chat_tx_for_view = chat_tx.clone();
        let window = cx
            .open_window(
                WindowOptions {
                    window_bounds: Some(WindowBounds::Windowed(bounds)),
                    ..Default::default()
                },
                |_window, cx| {
                    let email_field = TextField::new(cx, "admin@local", false, "admin@local");
                    let password_field = TextField::new(cx, "••••••••", true, "");
                    // S4: the chat composer entity is created here (needs
                    // `&mut App`, available at this point) and handed into
                    // `ChatState`; the subscription below is what turns its
                    // `ChatInputEvent::Submit` (Enter-to-send) into an
                    // actual `chat_ws::Command::Send`.
                    let chat_input =
                        ime_input::ChatInputState::new(cx, i18n::t(initial_locale, "native.chat.inputPlaceholder"));
                    let chat_input_for_sub = chat_input.clone();
                    cx.new(|cx| {
                        cx.subscribe(
                            &chat_input_for_sub,
                            |this: &mut RootView, _emitter, event: &ime_input::ChatInputEvent, cx| {
                                let ime_input::ChatInputEvent::Submit(content) = event;
                                this.chat.submit(content.clone());
                                // S4b: this listener is global (one
                                // subscription on the one shared composer
                                // entity — `dashboard_cards.rs`'s prompt bar
                                // reuses the SAME entity, see that module's
                                // doc comment), so navigating to the chat
                                // page here covers Enter-to-submit from
                                // EITHER page: submitting from `home`
                                // switches into `newChat` to show the
                                // exchange landing; submitting from
                                // `newChat` itself is a no-op reassignment.
                                this.active_page = "newChat";
                                cx.notify();
                            },
                        )
                        .detach();
                        RootView {
                            screen: if debug_page.is_some() { Screen::Shell } else { initial_screen },
                            locale: initial_locale,
                            ws_state: WsConnState::Disconnected,
                            email_field,
                            password_field,
                            active_page: debug_active_page.unwrap_or("home"),
                            active_prototype: debug_active_prototype
                                .unwrap_or(screens::prototypes::PROTOTYPES[0].id),
                            sidebar_collapsed: false,
                            session_tx: session_tx_for_view,
                            jwt: None,
                            refresh_token: None,
                            login_loading: false,
                            login_error: None,
                            chat: screens::chat::ChatState::new(chat_input, chat_tx_for_view),
                            dashboard: screens::dashboard::DashboardState::new(),
                            display_name: None,
                        }
                    })
                },
            )
            .expect("failed to open window");
        eprintln!("[main] window opened");

        // P0-2: macOS menu bar (App/View/Window/Help — see
        // `native_menu.rs`'s header comment for why this is a whole-module
        // `#[cfg(target_os = "macos")]` gate, not a partial one). Must come
        // after `open_window` — every menu action closure captures `window`
        // to reach `RootView` state, the same `WindowHandle::update` bridge
        // the poll loop below uses.
        native_menu::install(cx, window, initial_locale);

        // Same bridge pattern as Phase 0a's smoke test: poll the mpsc
        // channel from gpui's foreground executor and push updates into
        // the view. I/O stays on the background thread/executor; only
        // `Entity`/`Window` updates happen on the foreground executor,
        // never a direct cross-thread mutation.
        cx.spawn(async move |cx| loop {
            let mut session_dead = false;
            let mut chat_dead = false;
            match session_rx.try_recv() {
                Ok(event) => {
                    let _ = window.update(cx, |view, _window, cx| {
                        view.handle_session_event(event);
                        cx.notify();
                    });
                }
                Err(mpsc::TryRecvError::Empty) => {}
                Err(mpsc::TryRecvError::Disconnected) => session_dead = true,
            }
            // S4: drained in the same poll tick as the session channel —
            // one background-thread bridge loop for both managers, rather
            // than a second `cx.spawn` (they're independent enough not to
            // NEED separate loops, and one loop is simpler to reason about
            // than two racing against the same `window` handle).
            match chat_rx.try_recv() {
                Ok(event) => {
                    let _ = window.update(cx, |view, _window, cx| {
                        view.handle_chat_event(event);
                        cx.notify();
                    });
                }
                Err(mpsc::TryRecvError::Empty) => {}
                Err(mpsc::TryRecvError::Disconnected) => chat_dead = true,
            }
            // S4b: cheap no-op check (two field reads) on every tick — fires
            // the dashboard's seven RPCs exactly once per "arrived on the
            // home page" transition. See `screens/dashboard.rs::maybe_fetch`'s
            // doc comment for why this lives in the poll loop rather than in
            // `render` (which only ever gets `&RootView`, not `&mut`).
            let _ = window.update(cx, |view, _window, cx| {
                screens::dashboard::maybe_fetch(view, cx);
            });
            if session_dead && chat_dead {
                break;
            }
            cx.background_executor()
                .timer(Duration::from_millis(100))
                .await;
        })
        .detach();

        cx.activate(true);
    });
}
